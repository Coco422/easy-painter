export interface GenerationQuip {
  index: number
  text: string
  sequence: number
  nextAt: number
}

export function nextGenerationQuip(now: number, previous?: GenerationQuip, random: () => number = Math.random): GenerationQuip {
  // Exclude only this job's immediately previous line. Other jobs may naturally
  // draw the same line; they never share a batch seed, cursor or random deadline.
  const draw = Math.floor(random() * (GENERATION_QUIPS.length - (previous ? 1 : 0)))
  const index = previous && draw >= previous.index ? draw + 1 : draw
  return { index, text: GENERATION_QUIPS[index]!, sequence: (previous?.sequence ?? -1) + 1,
    nextAt: now + 4500 + Math.floor(random() * 3001) }
}
